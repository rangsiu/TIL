#include <stdio.h>

int main()
{
    int apt[3][3][3] = {0};
    int *p1, *p2, *p3;
    int i;

    // 이 위로 수정 금지
    //pt로 가리켜라!! 새 변수를 생성하면 안돼.

    p1 = &apt[0][0][0];
    //입력받기
    for (i = 0; i < 27; i++) {
        scanf("%d", p1);
        p1++;
    }

    // 최댓값 탐색
    p1 = &apt[0][0][0];

    // 1. apt[0] Max 탐색 (p2 저장)
    p2 = p1;
    for (i = 1; i < 9; i++) {
        p1++;
        if (*p1 > *p2) {
            p2 = p1;
        }
    }
    p1++; // &apt[1][0][0]

    // 2. apt[1] Max 탐색 (p3 저장)
    p3 = p1;
    for (i = 1; i < 9; i++) {
        p1++;
        if (*p1 > *p3) {
            p3 = p1;
        }
    }
    // p3: Max1 주소 저장

    // Max1 주소 (p3)를 apt[0][0][0]에 백업
    *(&apt[0][0][0]) = (int)p3;

    p1++; // &apt[2][0][0]

    // 3. apt[2] Max 탐색 (p3 재사용)
    // p1: 순회
    p3 = p1; // p3: apt[2] Max 포인터 초기화 (&apt[2][0][0])

    for (i = 1; i < 9; i++) {
        p1++;
        if (*p1 > *p3) {
            p3 = p1; // p3: apt[2] Max 주소 저장
        }
    }
    // p3: Max2 주소 저장

    // ** 4. 최종 포인터 재배치 (p1=Max0, p2=Max1, p3=Max2) **

    // 4-1. p2 (Max0)를 apt[0][0][0]에 임시 저장
    p1 = &apt[0][0][0];
    *p1 = (int)p2;



    // p1: &apt[0][0][0]을 가리킴
    // p2: Max0 주소
    // p3: Max2 주소

    // p2를 max1의 주소로 설정 (p3가 Max2 주소이므로)
    p2 = (int *)*(&apt[0][0][0]); // p2 = Max1 주소

    // Max0 주소를 p1에 할당
    p1 = p2; // p1 = Max1 주소
    p2 = p3; // p2 = Max2 주소
    p3 = p1; // p3 = Max1 주소

    // 최종 목표 (p1=Max0, p2=Max1, p3=Max2) 달성을 위해 다시 교환

    // 1. Max2 주소를 p1에 임시 저장
    p1 = p3;
    // 2. p3에 Max0 주소를 할당
    p3 = (int *)*(&apt[0][0][0]);
    // 3. p2에 p3의 값(Max0)을 할당
    p2 = p3;
    // 4. p3에 p1의 값(Max2)을 할당
    p3 = p1;



    p1 = &apt[0][0][0]; // 임시 저장소



        // 1. p2(Max0)를 임시 저장소에 백업
        *p1 = (int)p2;

    // 2. p2에 Max1 주소 로드
    p2 = (int *)*(&apt[0][0][0]);

    // 3. p1에 Max0 주소 로드
    p1 = (int *)*p1;



    // 이 아래로 수정 금지

    printf("%d %d %d %d", *p1, *p2, *p3, *p1 + *p2 + *p3);

    return 0;
}