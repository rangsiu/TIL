#include <stdio.h>

int main() {
    int A[10];
    int K;

    // 1. 입력 받기
    for (int i = 0; i < 10; i++) {
        scanf("%d", &A[i]);
    }
    scanf("%d", &K);

    // 2. K번 반복하여 전체를 오른쪽으로 1비트씩 시프트
    for (int k = 0; k < K; k++) {
        //k 세트만큼 이 모든 걸 반복.
        // 여기서는 가장 마지막 원소부터 거꾸로 처리하는 것이 논리적으로 편합니다.

        for (int i = 9; i >= 0; i--) {
            // 현재 칸의 비트를 오른쪽으로 1칸 밀기
            // 단, A[i-1]의 가장 낮은 비트(LSB)가 A[i]의 가장 높은 비트(MSB)로 와야 함

            A[i] = A[i] >> 1; // 자기 자신 시프트

            if (i > 0) {
                //하위 비트 제외 i는 0이 아님.
                // 앞 칸(A[i-1])의 마지막 비트가 1이라면, 현재 칸(A[i])의 8번째 비트(128)를 1로 만듦
                if (A[i - 1] & 1) {
                    A[i] = A[i] | 128; // 128은 이진수로 10000000
                }
            }
        }
    }

    // 3. 결과 출력
    for (int i = 0; i < 10; i++) {
        printf("%d ", A[i]);
    }

    return 0;
}